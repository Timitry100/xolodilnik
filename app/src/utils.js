export function daysUntil(expiryDate) {
  if (!expiryDate) return null;
  const d = new Date(expiryDate + 'T23:59:59');
  return Math.ceil((d - new Date()) / 86400000);
}

export function expiryStatus(d) {
  if (d === null || d === undefined) return { level: 'none', label: 'Срок не указан', icon: '⚪' };
  if (d < 0) return { level: 'expired', label: `Просрочен на ${-d} дн.`, icon: '🔴' };
  if (d === 0) return { level: 'today', label: 'Истекает сегодня', icon: '🟠' };
  if (d <= 3) return { level: 'soon', label: `Осталось ${d} дн.`, icon: '🟡' };
  if (d <= 7) return { level: 'week', label: `Осталось ${d} дн.`, icon: '🟢' };
  return { level: 'ok', label: `Осталось ${d} дн.`, icon: '🟢' };
}

export function fmtDate(iso) {
  if (!iso) return '';
  const [y, m, d] = iso.split('-');
  return `${d}.${m}.${y}`;
}

export function fmtKbju(p) {
  const parts = [];
  if (p.kcal != null) parts.push(`🔥 ${p.kcal} ккал`);
  if (p.protein != null) parts.push(`Б ${p.protein} г`);
  if (p.fat != null) parts.push(`Ж ${p.fat} г`);
  if (p.carbs != null) parts.push(`У ${p.carbs} г`);
  return parts;
}

export function guessCategory(name) {
  const n = String(name || '').toLowerCase();
  const rules = [
    [/молок|кефир|творог|йогурт|сметан|ряженк|простокваш|сыр(?!ок)|масл(о|яной)|сливк|бифидок|айран/, 'Молочное'],
    [/мясо|говядин|свинин|курин|куриц|индейк|фарш|колбас|сосис|ветчин|бекон|грудинк|окороч/, 'Мясо и птица'],
    [/рыб|лосос|семг|треск|минтай|сельд|тунец|креветк|кальмар|миди|икр/, 'Рыба и морепродукты'],
    [/овощ|помидор|огурец|капуст|морков|свекл|картофел|лук|чеснок|перец|кабачок|баклажан|салат|зелень|фрукт|яблок|банан|апельсин|лимон|груш|виноград|клубник|арбуз|дын|авакадо|авокадо/, 'Овощи и фрукты'],
    [/напит|вода|сок|компот|лимонад|кола|квас|чай|кофе|пиво|сидр|морс|газировк/, 'Напитки'],
    [/мук|крупа|рис|гречк|овсян|макарон|спагетти|лапш|соль|сахар|мук|подсолнечн|растительн|оливк|масло|консерв|горошек|кукуруз|томат|майонез|кетчуп|соус/, 'Бакалея'],
    [/заморож|пельмен|вареник|морожен|брокколи|полуфабрик/, 'Замороженное'],
    [/хлеб|батон|булк|булочк|багет|лаваш|тост|сухар|крекер|печень/, 'Хлеб и выпечка'],
    [/шоколад|конфет|торт|пирожн|вафл|мармелад|зефир|халв|пряник|леденец|батончик|драже/, 'Кондитерские изделия'],
  ];
  for (const [re, cat] of rules) {
    if (re.test(n)) return cat;
  }
  return 'Другое';
}
